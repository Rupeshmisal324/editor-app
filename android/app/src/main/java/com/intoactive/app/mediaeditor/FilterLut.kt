/**
 * Android side of the named filters, made to look the same as iOS.
 *
 * iOS's filters are Core Image chains (CIPhotoEffectChrome/Noir/...), and
 * several of them use tone curves that no ColorMatrix can reproduce. So
 * each filter is shipped as a 33³ colour lookup table rendered from the
 * iOS filters themselves (assets/filter_luts/<name>.lut, generated by
 * scripts/generate-filter-luts.swift). Layout: SIZE³ RGB bytes at
 * ((r * SIZE + g) * SIZE + b) * 3.
 *
 * The Filters panel's Strength and Saturation are folded into the table
 * ("baked"), in LINEAR light, because that is where iOS does them:
 * Strength is CIDissolveTransition and Saturation is CIColorControls,
 * both running in Core Image's linear working space. Saturation uses
 * CIColorControls' own luma weights (verified against Core Image).
 */
internal object FilterLut {
  const val SIZE = 33
  private const val ENTRY_COUNT = SIZE * SIZE * SIZE

  @Volatile private var assets: AssetManager? = null
  private val tables = ConcurrentHashMap<PhotoFilter, ByteArray>()

  fun init(context: Context) {
    assets = context.applicationContext.assets
  }

  private val srgbToLinear = FloatArray(256) { i ->
    val v = i / 255f
    if (v <= 0.04045f) v / 12.92f else ((v + 0.055f) / 1.055f).pow(2.4f)
  }

  private fun linearToSrgb8(linear: Float): Int {
    val v = linear.coerceIn(0f, 1f)
    val s = if (v <= 0.0031308f) v * 12.92f else 1.055f * v.pow(1f / 2.4f) - 0.055f
    return (s * 255f).roundToInt().coerceIn(0, 255)
  }

  /** The filter's full-strength table, or null for Original / a missing asset. */
  private fun table(filter: PhotoFilter): ByteArray? {
    val name = filter.lutAssetName ?: return null
    tables[filter]?.let { return it }
    val manager = assets ?: return null
    val bytes = runCatching { manager.open("filter_luts/$name.lut").use { it.readBytes() } }.getOrNull()
    if (bytes == null || bytes.size != ENTRY_COUNT * 3) return null
    tables[filter] = bytes
    return bytes
  }

  /** Strength + Saturation are snapped to whole percent so the cache
   *  (and the GPU texture) only rebuilds when the visible value changes. */
  data class Key(val filter: PhotoFilter, val strengthPct: Int, val saturationPct: Int)

  fun keyFor(filter: PhotoFilter, strength: Float, saturation: Float): Key? {
    if (filter == PhotoFilter.ORIGINAL) return null
    val key = Key(filter, (strength.coerceIn(0f, 1f) * 100).roundToInt(), (saturation.coerceIn(-1f, 1f) * 100).roundToInt())
    // 0% strength and no saturation change = untouched source.
    if (key.strengthPct == 0 && key.saturationPct == 0) return null
    return key
  }

  /** Packed 0xRRGGBB per entry, same index order as the asset. Null = identity. */
  fun baked(key: Key?): IntArray? {
    if (key == null) return null
    val src = table(key.filter) ?: return null
    val strength = key.strengthPct / 100f
    val saturation = 1f + key.saturationPct / 100f
    val out = IntArray(ENTRY_COUNT)
    val step = 255f / (SIZE - 1)
    var i = 0
    for (r in 0 until SIZE) {
      val ir = (r * step).roundToInt()
      for (g in 0 until SIZE) {
        val ig = (g * step).roundToInt()
        for (b in 0 until SIZE) {
          val ib = (b * step).roundToInt()
          val o = i * 3
          val fr = src[o].toInt() and 0xFF
          val fg = src[o + 1].toInt() and 0xFF
          val fb = src[o + 2].toInt() and 0xFF
          if (strength >= 1f && saturation == 1f) {
            out[i] = (fr shl 16) or (fg shl 8) or fb
          } else {
            // Strength: blend source -> filtered in linear light.
            var lr = srgbToLinear[ir] + (srgbToLinear[fr] - srgbToLinear[ir]) * strength
            var lg = srgbToLinear[ig] + (srgbToLinear[fg] - srgbToLinear[ig]) * strength
            var lb = srgbToLinear[ib] + (srgbToLinear[fb] - srgbToLinear[ib]) * strength
            if (saturation != 1f) {
              val luma = 0.2125f * lr + 0.7154f * lg + 0.0721f * lb
              lr = luma + (lr - luma) * saturation
              lg = luma + (lg - luma) * saturation
              lb = luma + (lb - luma) * saturation
            }
            out[i] = (linearToSrgb8(lr) shl 16) or (linearToSrgb8(lg) shl 8) or linearToSrgb8(lb)
          }
          i++
        }
      }
    }
    return out
  }

  // Per 8-bit value: lower grid index and fraction toward the next one.
  private val gridIndex = IntArray(256) { minOf((it * (SIZE - 1)) / 255, SIZE - 2) }
  private val gridFraction = FloatArray(256) { it * (SIZE - 1) / 255f - gridIndex[it] }

  /** Applies a baked table to every pixel (trilinear, same as the GPU
   *  path). Returns [source] itself when [table] is null. */
  fun apply(source: Bitmap, table: IntArray?): Bitmap {
    if (table == null) return source
    val width = source.width
    val height = source.height
    val pixels = IntArray(width * height)
    source.getPixels(pixels, 0, width, 0, 0, width, height)
    val strideG = SIZE
    val strideR = SIZE * SIZE
    for (p in pixels.indices) {
      val c = pixels[p]
      val r = (c shr 16) and 0xFF
      val g = (c shr 8) and 0xFF
      val b = c and 0xFF
      val r0 = gridIndex[r]; val g0 = gridIndex[g]; val b0 = gridIndex[b]
      val dr = gridFraction[r]; val dg = gridFraction[g]; val db = gridFraction[b]
      val base = r0 * strideR + g0 * strideG + b0
      val c000 = table[base]
      val c001 = table[base + 1]
      val c010 = table[base + strideG]
      val c011 = table[base + strideG + 1]
      val c100 = table[base + strideR]
      val c101 = table[base + strideR + 1]
      val c110 = table[base + strideR + strideG]
      val c111 = table[base + strideR + strideG + 1]
      var rgb = 0
      var shift = 16
      while (shift >= 0) {
        val v000 = (c000 shr shift) and 0xFF; val v001 = (c001 shr shift) and 0xFF
        val v010 = (c010 shr shift) and 0xFF; val v011 = (c011 shr shift) and 0xFF
        val v100 = (c100 shr shift) and 0xFF; val v101 = (c101 shr shift) and 0xFF
        val v110 = (c110 shr shift) and 0xFF; val v111 = (c111 shr shift) and 0xFF
        val v00 = v000 + (v001 - v000) * db
        val v01 = v010 + (v011 - v010) * db
        val v10 = v100 + (v101 - v100) * db
        val v11 = v110 + (v111 - v110) * db
        val v0 = v00 + (v01 - v00) * dg
        val v1 = v10 + (v11 - v10) * dg
        val v = (v0 + (v1 - v0) * dr + 0.5f).toInt().coerceIn(0, 255)
        rgb = rgb or (v shl shift)
        shift -= 8
      }
      pixels[p] = (c and -0x1000000) or rgb
    }
    val result = Bitmap.createBitmap(width, height, Bitmap.Config.ARGB_8888)
    result.setPixels(pixels, 0, width, 0, 0, width, height)
    return result
  }

  /** The table as a SIZE x SIZE² bitmap: x = b, y = r * SIZE + g. */
  fun toTextureBitmap(table: IntArray): Bitmap {
    val argb = IntArray(table.size) { -0x1000000 or table[it] }
    return Bitmap.createBitmap(argb, SIZE, SIZE * SIZE, Bitmap.Config.ARGB_8888)
  }
}

/** What the video shader needs, read fresh for every frame. */
internal data class FilterGpuParams(
  val filter: PhotoFilter,
  val strength: Float,
  val saturation: Float,
  val sharpness: Float,
)

/** Media3 video effect for the Filters panel: the filter lookup table
 *  (with Strength + Saturation baked in) followed by Sharpness. The same
 *  math as [FilterLut.apply] + the photo sharpen, on the GPU. [params] is
 *  re-read every frame, so slider changes show on the next frame without
 *  rebuilding the player's effects. */
@UnstableApi
internal class FilterLutEffect(private val params: () -> FilterGpuParams) : GlEffect {
  override fun toGlShaderProgram(context: Context, useHdr: Boolean): GlShaderProgram =
    FilterLutShaderProgram(params, useHdr)
}

@UnstableApi
private class FilterLutShaderProgram(
  private val params: () -> FilterGpuParams,
  useHdr: Boolean,
) : BaseGlShaderProgram(/* useHighPrecisionColorComponents= */ useHdr, /* texturePoolCapacity= */ 1) {
  private val glProgram: GlProgram = try {
    GlProgram(VERTEX_SHADER, FRAGMENT_SHADER)
  } catch (e: GlUtil.GlException) {
    throw VideoFrameProcessingException(e)
  }
  private val texelSize = FloatArray(2)
  private var lutTextureId = 0
  private var lutKey: FilterLut.Key? = null
  private var lutKeyApplied = false

  init {
    glProgram.setBufferAttribute(
      "aFramePosition",
      GlUtil.getNormalizedCoordinateBounds(),
      GlUtil.HOMOGENEOUS_COORDINATE_VECTOR_SIZE,
    )
  }

  override fun configure(inputWidth: Int, inputHeight: Int): Size {
    texelSize[0] = 1f / inputWidth
    texelSize[1] = 1f / inputHeight
    return Size(inputWidth, inputHeight)
  }

  /** Runs on the GL thread: rebuilds the table texture only when the
   *  filter / Strength / Saturation actually changed. */
  private fun updateLutTexture(p: FilterGpuParams) {
    val key = FilterLut.keyFor(p.filter, p.strength, p.saturation)
    if (lutKeyApplied && key == lutKey) return
    if (lutTextureId != 0) {
      GlUtil.deleteTexture(lutTextureId)
      lutTextureId = 0
    }
    lutKey = key
    lutKeyApplied = true
    val table = FilterLut.baked(key) ?: return
    val bitmap = FilterLut.toTextureBitmap(table)
    lutTextureId = GlUtil.createTexture(bitmap)
    bitmap.recycle()
  }

  override fun drawFrame(inputTexId: Int, presentationTimeUs: Long) {
    try {
      val p = params()
      updateLutTexture(p)
      glProgram.use()
      glProgram.setSamplerTexIdUniform("uTexSampler", inputTexId, /* texUnitIndex= */ 0)
      // The sampler needs a valid texture even when the table is off.
      glProgram.setSamplerTexIdUniform("uLut", if (lutTextureId != 0) lutTextureId else inputTexId, /* texUnitIndex= */ 1)
      glProgram.setFloatUniform("uLutEnabled", if (lutTextureId != 0) 1f else 0f)
      glProgram.setFloatUniform("uLutSize", FilterLut.SIZE.toFloat())
      // Same strength curve as the photo sharpenBitmap (amount * 1.5).
      glProgram.setFloatUniform("uSharpen", p.sharpness.coerceIn(0f, 1f) * 1.5f)
      glProgram.setFloatsUniform("uTexelSize", texelSize)
      glProgram.bindAttributesAndUniforms()
      GLES20.glDrawArrays(GLES20.GL_TRIANGLE_STRIP, /* first= */ 0, /* count= */ 4)
    } catch (e: GlUtil.GlException) {
      throw VideoFrameProcessingException(e, presentationTimeUs)
    }
  }

  override fun release() {
    super.release()
    try {
      if (lutTextureId != 0) GlUtil.deleteTexture(lutTextureId)
      lutTextureId = 0
      glProgram.delete()
    } catch (e: GlUtil.GlException) {
      throw VideoFrameProcessingException(e)
    }
  }

  companion object {
    private const val VERTEX_SHADER = """
attribute vec4 aFramePosition;
varying vec2 vTexSamplingCoord;
void main() {
  gl_Position = aFramePosition;
  vTexSamplingCoord = vec2(aFramePosition.x * 0.5 + 0.5, aFramePosition.y * 0.5 + 0.5);
}
"""

    // The table texture is SIZE wide x SIZE² tall (x = b, y = r * SIZE + g).
    // Two bilinear samples (the two red planes) + a mix = trilinear.
    private const val FRAGMENT_SHADER = """
precision highp float;
uniform sampler2D uTexSampler;
uniform sampler2D uLut;
uniform float uLutEnabled;
uniform float uLutSize;
uniform float uSharpen;
uniform vec2 uTexelSize;
varying vec2 vTexSamplingCoord;

vec3 lookup(vec3 c) {
  c = clamp(c, 0.0, 1.0);
  float n = uLutSize;
  float r = c.r * (n - 1.0);
  float r0 = min(floor(r), n - 2.0);
  float x = (c.b * (n - 1.0) + 0.5) / n;
  float g = c.g * (n - 1.0) + 0.5;
  vec3 lo = texture2D(uLut, vec2(x, (r0 * n + g) / (n * n))).rgb;
  vec3 hi = texture2D(uLut, vec2(x, ((r0 + 1.0) * n + g) / (n * n))).rgb;
  return mix(lo, hi, r - r0);
}

vec3 graded(vec2 uv) {
  vec3 c = texture2D(uTexSampler, uv).rgb;
  return uLutEnabled > 0.5 ? lookup(c) : c;
}

void main() {
  vec4 src = texture2D(uTexSampler, vTexSamplingCoord);
  vec3 c = uLutEnabled > 0.5 ? lookup(src.rgb) : src.rgb;
  if (uSharpen > 0.0) {
    vec3 avg = (graded(vTexSamplingCoord + vec2(uTexelSize.x, 0.0))
      + graded(vTexSamplingCoord - vec2(uTexelSize.x, 0.0))
      + graded(vTexSamplingCoord + vec2(0.0, uTexelSize.y))
      + graded(vTexSamplingCoord - vec2(0.0, uTexelSize.y))) * 0.25;
    c = clamp(c + (c - avg) * uSharpen, 0.0, 1.0);
  }
  gl_FragColor = vec4(c, src.a);
}
"""
  }
}
